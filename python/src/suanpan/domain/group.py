class NodeGroupGenerate(Group):
    """Range generator (C++ ``NodeGroup``/``ElementGroup``).

    The exported pool is ``start, start + interval, ..., end``.  Exactly
    like the C++ implementation a range with ``start > end`` stays empty.
    """

    keyword = "generate"
    summary = "generate a group from a numeric range"

    generated_type: str = Field(
        default="nodegroup", description="nodegroup or elementgroup"
    )
    start: int = Field(description="first tag in the range")
    interval: int | None = Field(
        default=None, description="step of the range (default 1)"
    )
    end: int | None = Field(default=None, description="last tag in the range")

    @model_validator(mode="after")
    def check_type(self) -> NodeGroupGenerate:
        if self.generated_type.strip().lower() not in {"nodegroup", "elementgroup"}:
            raise ValueError("generated_type must be 'nodegroup' or 'elementgroup'")
        return self

    def export_pool(self) -> list[int]:
        """Reproduce the tag pool the C++ parser would build."""
        interval = 1 if self.interval is None or self.interval == 0 else self.interval
        end = self.end
        if end is None:
            end = self.interval if self.interval is not None else self.start
        start, interval = self.start, interval
        if start == end:
            interval = 1
        if start < end and interval < 0 or start > end and interval > 0:
            interval = -interval
        pool: list[int] = []
        while start <= end:
            pool.append(start)
            start += interval
        return pool

    def to_commands(self) -> list[str]:
        interval = self.interval if self.interval is not None else 1
        end = self.end
        if end is None:
            end = self.interval if self.interval is not None else self.start
        return [
            _line(
                "generate",
                self.generated_type.strip().lower(),
                self.tag,
                self.start,
                interval,
                end,
            )
        ]


class NodeGroupGenerateByRule(Group):
    """DOF rule generator (C++ ``NodeGroup``)."""

    keyword = "generatebyrule"
    summary = "generate node group by DOF rule"

    dof: DofToken = Field(description="dof identifier driving the selection")
    rule: FloatList = Field(default_factory=list, description="rule values")

    def to_commands(self) -> list[str]:
        return [_line("generatebyrule", "nodegroup", self.tag, self.dof, self.rule)]


class NodeGroupGenerateByPoint(Group):
    """Point based generator (C++ ``NodeGroup``)."""

    keyword = "generatebypoint"
    summary = "generate node group between two points"

    values: FloatList = Field(
        default_factory=list, description="coordinates (even count)"
    )

    @model_validator(mode="after")
    def check_even(self) -> NodeGroupGenerateByPoint:
        if len(self.values) % 2:
            raise ValueError("generatebypoint requires an even number of values")
        return self

    def to_commands(self) -> list[str]:
        return [_line("generatebypoint", "nodegroup", self.tag, self.values)]


class NodeGroupGenerateByPlane(Group):
    """Plane based generator (C++ ``NodeGroup``)."""

    keyword = "generatebyplane"
    summary = "generate node group by plane"

    values: FloatList = Field(
        default_factory=list, description="plane description values"
    )

    @model_validator(mode="after")
    def check_nonempty(self) -> NodeGroupGenerateByPlane:
        if not self.values:
            raise ValueError("generatebyplane requires at least one value")
        return self

    def to_commands(self) -> list[str]:
        return [_line("generatebyplane", "nodegroup", self.tag, self.values)]
