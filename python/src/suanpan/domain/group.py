"""Group objects, mirroring ``Domain/Group/GroupParser.cpp``.

The ``group`` command family shares one dispatcher ``create_new_group``
whose first token selects the group type, so the exported line always
starts with the group type keyword itself (``nodegroup 1 2 3``) or with
the generator keyword followed by the generated type
(``generatebypoint nodegroup 1 ...``).
"""

from __future__ import annotations

from pydantic import Field, model_validator

from suanpan.base import SuanpanObject, format_value
from suanpan.toolbox.dof import DofToken
from suanpan.toolbox.format import FloatList, IntList

__all__ = [
    "CustomNodeGroup",
    "ElementGroup",
    "Group",
    "GroupGroup",
    "NodeGroup",
    "NodeGroupGenerate",
    "NodeGroupGenerateByPlane",
    "NodeGroupGenerateByPoint",
    "NodeGroupGenerateByRule",
]


def _line(*tokens: object) -> str:
    return " ".join(
        token if isinstance(token, str) else " ".join(format_value(token))
        for token in tokens
    ).strip()


class Group(SuanpanObject):
    """Base class of all groups."""

    command = "group"
    sp_abstract = True
    #: group keyword printed at the head of the line
    keyword = "nodegroup"


class NodeGroup(Group):
    """A plain list of node tags (C++ ``NodeGroup``)."""

    summary = "group of node tags"

    node_tags: IntList = Field(default_factory=list, description="node tags")

    def to_commands(self) -> list[str]:
        return [_line("nodegroup", self.tag, self.node_tags)]


class CustomNodeGroup(Group):
    """A node group generated by an expression (C++ ``CustomNodeGroup``)."""

