"""Bulk generated Material classes.

DO NOT EDIT BY HAND: generated by ``tools/generate.py`` from the parser
specs in ``specs/``, whose layouts and defaults come from ``Material/MaterialParser.cpp`` --
the only source of truth.

The generic export emits ``material <keyword> <tag> <required parameters>
<optional parameters up to the last one that differs from its default>
<trailing list>``, mirroring the eof-guarded token consumption of the
C++ handlers.
"""

from __future__ import annotations

from typing import ClassVar

from pydantic import Field

from suanpan.base import SuanpanObject, format_value
